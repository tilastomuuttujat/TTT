import fs from 'node:fs';
const file='artikkeli-visualisoinnit.json';
const data=JSON.parse(fs.readFileSync(file,'utf8'));
const articles=Array.isArray(data)?data:data.articles;
const a=articles.find(x=>x&&(x.id==='liikkumavaran-hyvinvointivaltio'||x.slug==='liikkumavaran-hyvinvointivaltio'));
if(!a) throw new Error('Article visualization config not found');
a.sections ||= {};
const wrong='miksi-liikkumavara-on-tulevaisuuden-hyvinvointia';
const right='miksi-tulevaisuuden-hyvinvointia';
const src=a.sections[wrong];
if(!src) throw new Error('Laboratory config not found under old section id');
const labs=Array.isArray(src)?src.filter(x=>x&&x.type==='margin-lab'):(src.type==='margin-lab'?[src]:[]);
if(!labs.length) throw new Error('margin-lab not found');
const current=a.sections[right];
if(!current) a.sections[right]=labs.length===1?labs[0]:labs;
else if(Array.isArray(current)) { for(const lab of labs) if(!current.some(x=>x&&x.type==='margin-lab')) current.push(lab); }
else if(current.type!=='margin-lab') a.sections[right]=[current,...labs];
delete a.sections[wrong];
fs.writeFileSync(file,JSON.stringify(data,null,2)+'\n');
console.log('Moved margin-lab to',right);
